# ============================================================
# ДОПОЛНИТЕЛЬНАЯ НОРМАЛИЗАЦИЯ ТЕКСТА
# ============================================================

def _clean_name(name: str) -> str:
    """
    Подготавливает название перед поиском алиаса.
    """

    if not name:
        return ""

    value = str(name).strip()

    # HTML entities / лишние пробелы
    value = re.sub(r"\s+", " ", value)

    # Неразрывный пробел
    value = value.replace("\xa0", " ")

    # Разные виды тире
    value = value.replace("–", "-")
    value = value.replace("—", "-")

    # Убираем пробелы вокруг дефиса
    value = re.sub(r"\s*-\s*", "-", value)

    # Регистр
    value = value.lower().strip()

    return value


# ============================================================
# ОСНОВНАЯ ФУНКЦИЯ
# ============================================================

def normalize_team_name(
    name: Optional[str],
    *,
    strict: bool = False
) -> Optional[str]:
    """
    Преобразует название команды в canonical name.

    Пример:

        normalize_team_name("Динамо (Махачкала)")
            -> "Динамо Махачкала"

        normalize_team_name("Спартак Москва")
            -> "Спартак"

    strict=False:
        неизвестное название возвращается очищенным
        оригинальным текстом.

    strict=True:
        неизвестное название возвращает None.

    Это позволяет парсеру не создавать ложную команду.
    """

    if not name:
        return None

    original = str(name).strip()

    if not original:
        return None

    cleaned = _clean_name(original)

    # Прямое совпадение
    if cleaned in TEAM_ALIASES:
        return TEAM_ALIASES[cleaned]

    # Проверяем canonical names
    for canonical in CANONICAL_TEAMS:
        if cleaned == _clean_name(canonical):
            return canonical

    # Частые служебные приставки
    stripped = re.sub(
        r"^(фк|пфк|фк\s+)",
        "",
        cleaned
    ).strip()

    if stripped in TEAM_ALIASES:
        return TEAM_ALIASES[stripped]

    # Если источник неизвестен
    if strict:
        return None

    return original


# ============================================================
# ДВЕ КОМАНДЫ
# ============================================================

def normalize_team_names(
    home: Optional[str],
    away: Optional[str],
    *,
    strict: bool = False
) -> Tuple[Optional[str], Optional[str]]:
    """
    Нормализует обе команды матча.
    """

    return (
        normalize_team_name(home, strict=strict),
        normalize_team_name(away, strict=strict),
    )


# ============================================================
# ПРОВЕРКА ЯВЛЯЕТСЯ ЛИ КОМАНДА РПЛ
# ============================================================

def is_rpl_team(name: Optional[str]) -> bool:
    """
    Проверяет, является ли название известной командой FAJ РПЛ.
    """

    normalized = normalize_team_name(name, strict=True)

    return normalized in CANONICAL_TEAMS


# ============================================================
# ПОЛУЧЕНИЕ CANONICAL NAME
# ============================================================

def canonical_team(name: Optional[str]) -> Optional[str]:
    """
    Удобный alias для normalize_team_name().
    """

    return normalize_team_name(name, strict=True)


# ============================================================
# ПОЛУЧЕНИЕ ВСЕХ КОМАНД
# ============================================================

def get_canonical_teams() -> list[str]:
    """
    Возвращает список canonical-команд FAJ.
    """

    return sorted(CANONICAL_TEAMS)


# ============================================================
# ДИАГНОСТИКА
# ============================================================

def normalization_diagnostic(names: list[str]) -> list[dict]:
    """
    Проверяет список названий и показывает,
    во что они преобразуются.

    Используется для диагностики новых источников.
    """

    result = []

    for name in names:
        normalized = normalize_team_name(name, strict=True)

        result.append({
            "source_name": name,
            "normalized_name": normalized,
            "recognized": normalized is not None,
        })

    return result


