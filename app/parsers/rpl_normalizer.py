def clean_name(name: str) -> str:
    if not name:
        return ""

    name = str(name).replace("\xa0", " ")
    name = name.strip()
    name = re.sub(r"\s+", " ", name)

    # Убираем кавычки
    name = name.replace('"', "")
    name = name.replace("«", "")
    name = name.replace("»", "")

    return name.strip()


def normalize_team_name(name: str) -> str:
    """
    Возвращает каноническое название команды.
    """

    name = clean_name(name)

    if not name:
        return ""

    if name in TEAM_ALIASES:
        return TEAM_ALIASES[name]

    # Попытка без точек
    simplified = name.replace(".", "")
    if simplified in TEAM_ALIASES:
        return TEAM_ALIASES[simplified]

    return name


def normalize_team_names(home: str, away: str) -> tuple[str, str]:
    return (
        normalize_team_name(home),
        normalize_team_name(away),
    )


def is_known_team(name: str) -> bool:
    return normalize_team_name(name) in CANONICAL_TEAMS
